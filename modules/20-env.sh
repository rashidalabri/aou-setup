# Resolve workspace-specific values with the Workbench CLI and persist them.
#   ~/.aou/env.sh    bash exports, sourced from ~/.bashrc
#   ~/.aou/env.list  KEY=VALUE lines for Python/R (e.g. readRenviron("~/.aou/env.list"))
# Values that the platform already provides (via ~/load-env.sh) take precedence.

have jq || die "jq is required"

workspace_json="$(wb workspace describe --format=json)"
resources_json="$(wb resource list --format=json)"

project="$(jq -r '.googleProjectId' <<<"$workspace_json")"
[[ -n "$project" && "$project" != null ]] || die "Could not determine the workspace GCP project"

bucket_for() {  # gs:// URL of the bucket resource with this id, or empty
  jq -r --arg id "$1" '.[] | select(.resourceType=="GCS_BUCKET" and .id==$id) | "gs://\(.bucketName)"' \
    <<<"$resources_json" | head -n1
}

# Latest CDR dataset among the workspace resources (IDs look like C2025Q4R6).
resolved_cdr="$(jq -r '
  [ .[] | select(.resourceType=="BQ_DATASET" or .resourceType=="BIGQUERY_DATASET")
        | select(.datasetId | test("^C[0-9]{4}Q[0-9]+R[0-9]+$"))
        | {ref: "\(.projectId).\(.datasetId)",
           key: (.datasetId | capture("^C(?<y>[0-9]+)Q(?<q>[0-9]+)R(?<r>[0-9]+)$") | [(.y|tonumber),(.q|tonumber),(.r|tonumber)])} ]
  | sort_by(.key) | last | .ref // empty' <<<"$resources_json")"

platform_cdr="$(sed -n 's/^export WORKSPACE_CDR=//p' "$HOME/.aou-env" 2>/dev/null | tr -d '"' || true)"
cdr="${platform_cdr:-$resolved_cdr}"

# The cohort-builder index dataset (e.g. C2025Q4R6_index_061026) sits next to the CDR.
cdr_index=""
if [[ -n "$cdr" ]]; then
  cdr_index="$(bq ls --project_id "${cdr%%.*}" --max_results 1000 --format=json 2>/dev/null \
    | jq -r --arg p "${cdr#*.}_index_" '[.[].datasetReference.datasetId | select(startswith($p))] | sort | last // empty' \
    || true)"
  if [[ -n "$cdr_index" ]]; then cdr_index="${cdr%%.*}.$cdr_index"; fi
fi

workspace_bucket="$(bucket_for workspace-bucket)"
if [[ -z "$workspace_bucket" ]]; then
  # Workspaces migrated from Researcher Workbench 1.0 carry an rw-migration-* bucket.
  workspace_bucket="$(jq -r '.[] | select(.resourceType=="GCS_BUCKET" and (.id|startswith("rw-migration"))) | "gs://\(.bucketName)"' \
    <<<"$resources_json" | head -n1)"
fi
temp_bucket="$(bucket_for temporary-workspace-bucket)"
tutorial_bucket="$(bucket_for aou-tutorial-notebooks)"

# Local gcsfuse mount of the Controlled Tier data bucket, if mounted.
ct_mount="$(find "$HOME/workspace" -mindepth 1 -maxdepth 2 -type d -name 'vwb-aou-datasets-controlled*' -print -quit 2>/dev/null || true)"

pet_sa="$(jq -r '.user.petSAEmail // empty' "$HOME/.workbench/context.json" 2>/dev/null || true)"
[[ -n "$pet_sa" ]] || pet_sa="$(gcloud config get-value account 2>/dev/null || true)"

docker_repo="${ARTIFACT_REGISTRY_DOCKER_REPO:-$AOU_DEFAULT_DOCKER_REPO}"
cromwell_home="/opt/workbench-tools/binaries/share/cromwell"

vars=(
  GOOGLE_PROJECT="$project"
  GOOGLE_CLOUD_PROJECT="$project"
  WORKSPACE_CDR="$cdr"
  WORKSPACE_CDR_INDEX="$cdr_index"
  WORKSPACE_BUCKET="$workspace_bucket"
  WORKSPACE_TEMP_BUCKET="$temp_bucket"
  AOU_TUTORIAL_BUCKET="$tutorial_bucket"
  AOU_CT_MOUNT="$ct_mount"
  AOU_REGION="$AOU_REGION"
  ARTIFACT_REGISTRY_DOCKER_REPO="$docker_repo"
  PET_SA_EMAIL="$pet_sa"
  CROMWELL_JAR="$cromwell_home/cromwell.jar"
  WOMTOOL_JAR="$cromwell_home/womtool.jar"
)

mkdir -p "$AOU_HOME"
{
  echo "# Generated by aou-claude-setup on $(date -u +%Y-%m-%dT%H:%MZ). Re-run setup.sh to refresh."
  for kv in "${vars[@]}"; do
    key="${kv%%=*}" val="${kv#*=}"
    if [[ -n "$val" ]]; then printf 'export %s=%q\n' "$key" "$val"; fi
  done
} > "$AOU_ENV_FILE"
for kv in "${vars[@]}"; do
  if [[ -n "${kv#*=}" ]]; then printf '%s="%s"\n' "${kv%%=*}" "${kv#*=}"; fi
done > "$AOU_ENV_LIST"

upsert_block "$HOME/.bashrc" "# BEGIN aou-claude-setup" "# END aou-claude-setup" \
'for _aou_f in "$HOME/.aou/env.sh" "$HOME/.aou/aou_dsub.bash"; do
  if [ -f "$_aou_f" ]; then source "$_aou_f"; fi
done
unset _aou_f'

for kv in "${vars[@]}"; do
  key="${kv%%=*}" val="${kv#*=}"
  if [[ -n "$val" ]]; then ok "$key=$val"; else warn "$key is not set"; fi
done
[[ -n "$workspace_bucket" ]] || info "Without WORKSPACE_BUCKET, outputs and workflow configs have nowhere to go. Run: ./setup.sh --create-buckets"
info "Wrote $AOU_ENV_FILE and $AOU_ENV_LIST; ~/.bashrc sources them."
